    """.filter { !$0.isWhitespace && !$0.isNewline })

    /// 文字裡出現的簡體字（去重、保留出現順序）。
    static func simplifiedCharacters(in text: String) -> [Character] {
        var seen = Set<Character>()
        var found: [Character] = []
        for ch in text where simplifiedOnly.contains(ch) && !seen.contains(ch) {
            seen.insert(ch)
            found.append(ch)
        }
        return found
    }

    static func containsSimplified(_ text: String) -> Bool {
        text.contains { simplifiedOnly.contains($0) }
    }

    /// 給重試用的補充指令，明確點名犯規的字。
    static func correctionInstruction(for offenders: [Character]) -> String {
        let list = offenders.map(String.init).joined(separator: "、")
        return """

        ⚠️ 上一次的輸出混進了簡體字：\(list)
        請重新輸出一次，全部改成台灣慣用的繁體中文。再次強調：整份 JSON 的每一個字元都必須是繁體，一個簡體字都不准出現。
        """
    }
